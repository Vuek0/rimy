"""Chat texts in the learner's base language (ru / uz / en).

The language is set once per update (DbMiddleware → set_lang(user.native_lang)) in a context variable,
so any handler or helper just calls tr("key") without passing the language around. Jobs outside an
update (reminders) set it for each user themselves. Admin-only texts (/admin, backups) stay Russian.
"""

import random
from contextvars import ContextVar

_lang: ContextVar[str] = ContextVar("lang", default="ru")


def set_lang(code: str) -> None:
    _lang.set(code if code in TEXTS else "ru")


def current() -> str:
    return _lang.get()


def tr(key: str, **kw: object) -> str:
    return tr_in(current(), key, **kw)


def tr_in(lang: str, key: str, **kw: object) -> str:
    """tr() for an explicit language (the Mini App API runs outside bot updates)."""
    value = TEXTS.get(lang, TEXTS["ru"]).get(key, TEXTS["ru"][key])
    text = random.choice(value) if isinstance(value, list) else value
    return text.format(**kw) if kw else text


